    private static String checkedExecution() {
        return """
                /- Generated by `julc verify init`; explicit semantics and exhaustion API. -/
                import PlutusCore.Default
                import PlutusCore.UPLC.CekMachine
                import PlutusCore.UPLC.Utils

                namespace JulcGenerated.CheckedExecution

                open PlutusCore.Default
                open PlutusCore.UPLC.CekMachine
                open PlutusCore.UPLC.Term

                inductive CheckedResult where
                  | finished : State → CheckedResult
                  | stepExhausted : State → CheckedResult
                deriving Repr

                def runStepsChecked
                    (semanticsVariant : BuiltinSemanticsVariant)
                    (state : State) : Nat → CheckedResult
                  | 0 =>
                      match state with
                      | .Halt _ | .Error => .finished state
                      | _ => .stepExhausted state
                  | Nat.succ remaining =>
                      match state with
                      | .Halt _ | .Error => .finished state
                      | _ => runStepsChecked semanticsVariant
                          (step semanticsVariant state) remaining

                def executeProgramChecked
                    (semanticsVariant : BuiltinSemanticsVariant)
                    (program : Program)
                    (params : List Term)
                    (fuel : Nat) : CheckedResult :=
                  match program with
                  | .Program _ body => runStepsChecked semanticsVariant
                      (initialState (applyParams body params)) fuel

                /-- Generated Plutus V3/PV11 workspaces select semantics variant E. -/
                def executePlutusV3Pv11Checked : Program → List Term → Nat → CheckedResult :=
                  executeProgramChecked .defaultFunSemanticsVariantE

                def isSuccessful : CheckedResult → Prop
                  | .finished (.Halt _) => True
                  | _ => False

                def isEvaluationError : CheckedResult → Prop
                  | .finished .Error => True
                  | _ => False

                def isStepExhausted : CheckedResult → Prop
                  | .stepExhausted _ => True
                  | _ => False

                end JulcGenerated.CheckedExecution
                """;
    }

    private static String propertyTemplates() {
        return """
                /- Generated by `julc verify init`; reusable predicates, not theorem claims. -/
                import CardanoLedgerApi.V3

                namespace JulcGenerated.PropertyTemplates

                open CardanoLedgerApi.IsData.Class
                open CardanoLedgerApi.V3
                open PlutusCore.ByteString (ByteString)
                open PlutusCore.Data (Data)
                open PlutusCore.Integer (Integer)

                def firstSignerAuthorized (authority : ByteString) (ctx : ScriptContext) : Prop :=
                  match ctx.scriptContextTxInfo.txInfoSignatories with
                  | signer :: _ => signer = authority
                  | [] => False

                def firstInputValuePreserved (ctx : ScriptContext) : Prop :=
                  match ctx.scriptContextTxInfo.txInfoInputs,
                      ctx.scriptContextTxInfo.txInfoOutputs with
                  | input :: _, output :: _ =>
                      input.txInInfoResolved.txOutValue = output.txOutValue
                  | _, _ => False

                def firstOutputCommitsTo
                    (ref : CardanoLedgerApi.V3.Tx.TxOutRef)
                    (nextState : Integer)
                    (ctx : ScriptContext) : Prop :=
                  match ctx.scriptContextTxInfo.txInfoOutputs with
                  | output :: _ => output.txOutDatum =
                      .OutputDatum (Data.Constr 0 [IsData.toData ref, Data.I nextState])
                  | [] => False

                end JulcGenerated.PropertyTemplates
                """;
    }

    private static String validatorModule(
            String leanId, String artifactId, String purpose, int fuel) {
        String prepInputs = purpose.equals("spending") ? "spendingInputs" : "mintingInputs";
        return """
                /- Generated by `julc verify init`; specialize the property before claiming proof. -/
                import PlutusCore.UPLC
                import CardanoLedgerApi.V3
                import Blaster
                import GeneratedSchemas
                import PropertyTemplates
                import CheckedExecution
                import SecurityProperty

                namespace JulcGenerated.%s

                open CardanoLedgerApi.V3
                open PlutusCore.UPLC.Utils
                open JulcGenerated.UserProperty

                #import_uplc validator PlutusV3 double_cbor_hex
                  "artifacts/%s.compiledCode.hex"
                #prep_uplc appliedValidator validator %s %d

                /-- An explicit, currently unproved obligation; no theorem is generated. -/
                def verificationObligation : Prop :=
                  ∀ ctx : ScriptContext,
                    PlutusCore.UPLC.Utils.isSuccessful (appliedValidator.prop ctx) →
                    securityProperty ctx

                end JulcGenerated.%s
                """.formatted(leanId, artifactId, prepInputs, fuel, leanId);
    }

    private static String securityProperty() {
        return """
                /- Created by `julc verify init`; user-owned and preserved by `--force`. -/
                import CardanoLedgerApi.V3
                import PropertyTemplates

                namespace JulcGenerated.UserProperty

                open CardanoLedgerApi.V3

                /-- Replace with the reviewed, contract-specific security property. -/
                def securityProperty (_ctx : ScriptContext) : Prop := False

                end JulcGenerated.UserProperty
                """;
    }

    private static String verifyScript(
            String leanId, String artifactId, String compiledCodeSha256) {
        return """
                #!/usr/bin/env bash
                set -euo pipefail

                SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
                VERIFY_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
                if [[ -d "${HOME}/.elan/bin" ]]; then
                  export PATH="${HOME}/.elan/bin:${PATH}"
                fi
                cd "${VERIFY_DIR}"

                for tool in lake lean rg z3 git xxd; do
                  command -v "${tool}" >/dev/null 2>&1 || {
                    echo "COULD-NOT-EVALUATE: missing ${tool}" >&2
                    exit 2
                  }
                done

                [[ "$(lean --version | head -n 1)" == *"4.24.0"* ]] || {
                  echo "COULD-NOT-EVALUATE: expected Lean 4.24.0" >&2
                  exit 2
                }
                [[ "$(z3 --version)" == *"4.15.2"* ]] || {
                  echo "COULD-NOT-EVALUATE: expected Z3 4.15.2" >&2
                  exit 2
                }

                if command -v sha256sum >/dev/null 2>&1; then
                  actual_artifact_hash="$(tr -d '[:space:]' < artifacts/%s.compiledCode.hex | xxd -r -p | sha256sum | awk '{print $1}')"
                else
                  command -v shasum >/dev/null 2>&1 || {
                    echo "COULD-NOT-EVALUATE: missing SHA-256 tool" >&2
                    exit 2
                  }
                  actual_artifact_hash="$(tr -d '[:space:]' < artifacts/%s.compiledCode.hex | xxd -r -p | shasum -a 256 | awk '{print $1}')"
                fi
                [[ "${actual_artifact_hash}" == "%s" ]] || {
                  echo "COULD-NOT-EVALUATE: compiledCode artifact hash mismatch" >&2
                  exit 2
                }

                if rg -n '(^|[[:space:]])(sorry|admit)([[:space:]]|$)' --glob '*.lean' .; then
                  echo "COULD-NOT-EVALUATE: generated project contains sorry or admit" >&2
                  exit 2
                fi

                lake build GeneratedVerificationSupport
                while IFS=' ' read -r package expected; do
                  actual="$(git -C ".lake/packages/${package}" rev-parse HEAD)"
                  [[ "${actual}" == "${expected}" ]] || {
                    echo "COULD-NOT-EVALUATE: ${package} revision mismatch" >&2
                    exit 2
                  }
                done <<'PINS'
                Blaster %s
                PlutusCore %s
                CardanoLedgerApi %s
                PINS
                mkdir -p .lake/build/lib/lean
                lake env lean -o .lake/build/lib/lean/GeneratedSchemas.olean GeneratedSchemas.lean
                lake env lean -o .lake/build/lib/lean/PropertyTemplates.olean PropertyTemplates.lean
                lake env lean -o .lake/build/lib/lean/CheckedExecution.olean CheckedExecution.lean
                lake env lean -o .lake/build/lib/lean/SecurityProperty.olean SecurityProperty.lean
                lake env lean -o .lake/build/lib/lean/%sVerification.olean %sVerification.lean

                echo "COULD-NOT-EVALUATE: workspace compiles; specialize securityProperty and add a theorem plus negative control"
                exit 2
                """.formatted(artifactId, artifactId, compiledCodeSha256,
                BLASTER_REV, PLUTUS_CORE_REV, LEDGER_API_REV, leanId, leanId);
    }

