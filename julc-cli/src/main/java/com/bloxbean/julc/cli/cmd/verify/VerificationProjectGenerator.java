    static SchemaGeneration generateSchemas(JsonNode definitions, JsonNode validator)
            throws UnsupportedVerificationException {
        if (!definitions.isObject()) {
            throw new UnsupportedVerificationException("Blueprint definitions must be an object");
        }

        Set<String> roots = new LinkedHashSet<>();
        collectEntrySchemaRoot(validator.path("datum").path("schema"), roots);
        collectEntrySchemaRoot(validator.path("redeemer").path("schema"), roots);
        if (roots.isEmpty()) {
            throw new UnsupportedVerificationException(
                    "Validator has no named datum or redeemer schema references");
        }

        Map<String, JsonNode> all = new LinkedHashMap<>();
        definitions.fields().forEachRemaining(entry -> all.put(entry.getKey(), entry.getValue()));
        Set<String> needed = new LinkedHashSet<>();
        for (String root : roots.stream().sorted().toList()) {
            collectNeeded(root, all, needed, new HashSet<>());
        }

        Map<String, Set<String>> allDependencies = namedDependencyGraph(needed, all);
        for (List<String> group : dependencyGroups(allDependencies)) {
            boolean recursive = group.size() > 1
                    || allDependencies.getOrDefault(group.getFirst(), Set.of())
                            .contains(group.getFirst());
            if (recursive && group.stream()
                    .anyMatch(name -> !requiresNamedDefinition(all.get(name)))) {
                throw new UnsupportedVerificationException(
                        "Recursive schema aliases must use named constructor definitions: " + group);
            }
        }

        Map<String, String> names = new LinkedHashMap<>();
        Set<String> normalized = new HashSet<>();
        for (String name : needed) {
            JsonNode schema = all.get(name);
            if (!requiresNamedDefinition(schema)) {
                continue;
            }
            if (!hasIdentifierCharacters(name)) {
                throw new UnsupportedVerificationException(
                        "Schema name cannot form a Lean identifier: '" + name + "'");
            }
            String leanName = leanTypeName(name);
            if (RESERVED_TYPE_NAMES.contains(leanName)) {
                throw new UnsupportedVerificationException(
                        "Schema name conflicts with generated Lean imports at '" + leanName + "'");
            }
            if (!normalized.add(leanName)) {
                throw new UnsupportedVerificationException(
                        "Schema names collide after Lean normalization at '" + leanName + "'");
            }
            names.put(name, leanName);
        }

        var source = new StringBuilder();
        source.append("/- ").append(GENERATED_MARKER).append(" -/\n")
                .append("import CardanoLedgerApi.IsData.Class\n\n")
                .append("namespace JulcGenerated.Schemas\n\n")
                .append("open CardanoLedgerApi.IsData.Class\n")
                .append("open PlutusCore.ByteString (ByteString)\n")
                .append("open PlutusCore.Data (Data)\n")
                .append("open PlutusCore.Integer (Integer)\n\n")
                .append(containerSupport());

        Map<String, Set<String>> dependencyGraph = namedDependencyGraph(names.keySet(), all);
        for (List<String> group : dependencyGroups(dependencyGraph)) {
            boolean recursive = group.size() > 1
                    || dependencyGraph.getOrDefault(group.getFirst(), Set.of())
                            .contains(group.getFirst());
            if (recursive) {
                validateProductiveSchemas(group, all);
                source.append(generateRecursiveGroup(group, all, names));
            } else {
                String original = group.getFirst();
                source.append(generateDefinition(original, names.get(original), all, names));
            }
        }
        source.append("end JulcGenerated.Schemas\n");

        Map<String, String> leanTypes = new LinkedHashMap<>();
        for (String original : needed) {
            leanTypes.put(original,
                    schemaType(all.get(original), all, names, original, true));
        }
        return new SchemaGeneration(source.toString(), leanTypes);
    }

    /**
     * Prevents the carried schema-1 type graph and blueprint-derived Lean codecs from
     * assigning different names, tags, arities, or field positions to the same value.
     */
    static void validateProjectedTypesAgainstBlueprint(
            ProjectedContractTypes projection, JsonNode definitions, JsonNode validator)
            throws UnsupportedVerificationException {
        if (!definitions.isObject()) {
            throw new UnsupportedVerificationException("Blueprint definitions must be an object");
        }
        Map<String, JsonNode> all = new LinkedHashMap<>();
        definitions.fields().forEachRemaining(entry -> all.put(entry.getKey(), entry.getValue()));
        var stableToBlueprint = new HashMap<String, String>();
        var blueprintToStable = new HashMap<String, String>();

        JsonNode datum = validator.path("datum").path("schema");
        if (projection.datumType() == null) {
            if (!datum.isMissingNode()) {
                throw new UnsupportedVerificationException(
                        "Projected contract has no datum but blueprint publishes one");
            }
        } else {
            matchProjectedSchema(projection.datumType(), datum, projection, all,
                    stableToBlueprint, blueprintToStable, "datum");
        }
        matchProjectedSchema(projection.redeemerType(),
                validator.path("redeemer").path("schema"), projection, all,
                stableToBlueprint, blueprintToStable, "redeemer");

        JsonNode parameters = validator.path("parameters");
        int blueprintParameterCount = parameters.isArray() ? parameters.size() : 0;
        if (blueprintParameterCount != projection.parameters().size()) {
            throw new UnsupportedVerificationException(
                    "Projected parameter count does not match blueprint");
        }
        for (int index = 0; index < blueprintParameterCount; index++) {
            var parameter = projection.parameters().get(index);
            JsonNode published = parameters.get(index);
            if (published.has("title")
                    && !parameter.name().equals(published.path("title").asText())) {
                throw new UnsupportedVerificationException(
                        "Projected parameter name does not match blueprint at index " + index);
            }
            matchProjectedSchema(parameter.type(), published.path("schema"), projection, all,
                    stableToBlueprint, blueprintToStable, "parameter " + parameter.name());
        }

        if (stableToBlueprint.size() != projection.definitions().size()) {
            throw new UnsupportedVerificationException(
                    "Projected nominal graph is not fully reachable from blueprint roots");
        }
    }

    private static void matchProjectedSchema(
            VerificationTypeRef type,
            JsonNode schema,
            ProjectedContractTypes projection,
            Map<String, JsonNode> definitions,
            Map<String, String> stableToBlueprint,
            Map<String, String> blueprintToStable,
            String path) throws UnsupportedVerificationException {
        if (schema == null || schema.isMissingNode()) {
            throw projectedSchemaMismatch(path, "schema is missing");
        }
        switch (type) {
            case BuiltinTypeRef builtin -> matchProjectedBuiltin(builtin, schema, path);
            case LedgerTypeRef ignored -> throw projectedSchemaMismatch(
                    path, "ledger types cannot appear in compiler contract projection");
            case OptionalTypeRef optional -> {
                JsonNode value = optionalValueSchema(schema);
                if (value == null) throw projectedSchemaMismatch(path, "expected Optional");
                matchProjectedSchema(optional.elementType(), value, projection, definitions,
                        stableToBlueprint, blueprintToStable, path + ".Some");
            }
            case ListTypeRef list -> {
                if (!"list".equals(schema.path("dataType").asText())
                        || schema.path("items").isMissingNode()) {
                    throw projectedSchemaMismatch(path, "expected list");
                }
                matchProjectedSchema(list.elementType(), schema.path("items"), projection,
                        definitions, stableToBlueprint, blueprintToStable, path + "[]");
            }
            case AssocMapTypeRef map -> {
                if (!"map".equals(schema.path("dataType").asText())
                        || schema.path("keys").isMissingNode()
                        || schema.path("values").isMissingNode()) {
                    throw projectedSchemaMismatch(path, "expected association map");
                }
                matchProjectedSchema(map.keyType(), schema.path("keys"), projection,
                        definitions, stableToBlueprint, blueprintToStable, path + ".key");
                matchProjectedSchema(map.valueType(), schema.path("values"), projection,
                        definitions, stableToBlueprint, blueprintToStable, path + ".value");
            }
            case NominalTypeRef nominal -> matchProjectedNominal(nominal, schema, projection,
                    definitions, stableToBlueprint, blueprintToStable, path);
        }
    }

    private static void matchProjectedBuiltin(
            BuiltinTypeRef type, JsonNode schema, String path)
            throws UnsupportedVerificationException {
        boolean matches = switch (type.builtin()) {
            case INTEGER -> "integer".equals(schema.path("dataType").asText());
            case BYTE_STRING, STRING -> "bytes".equals(schema.path("dataType").asText());
            case BOOLEAN -> isBooleanSchema(schema);
            case UNIT -> isConstructor(schema, "Unit", 0, 0);
            case DATA -> "Any Plutus data.".equals(schema.path("description").asText())
                    && schema.path("dataType").isMissingNode();
        };
        if (!matches) {
            throw projectedSchemaMismatch(path,
                    "expected compiler type " + type.builtin());
        }
    }

    private static void matchProjectedNominal(
            NominalTypeRef nominal,
            JsonNode schema,
            ProjectedContractTypes projection,
            Map<String, JsonNode> definitions,
            Map<String, String> stableToBlueprint,
            Map<String, String> blueprintToStable,
            String path) throws UnsupportedVerificationException {
        String reference = schema.path("$ref").asText(null);
        if (reference == null) {
            throw projectedSchemaMismatch(path, "expected named schema reference");
        }
        String blueprintName = referenceName(reference);
        JsonNode definition = definitions.get(blueprintName);
        if (definition == null) {
            throw projectedSchemaMismatch(path, "dangling blueprint reference " + blueprintName);
        }
        String previousBlueprint = stableToBlueprint.putIfAbsent(
                nominal.stableId(), blueprintName);
        if (previousBlueprint != null && !previousBlueprint.equals(blueprintName)) {
            throw projectedSchemaMismatch(path,
                    "one nominal ID maps to multiple blueprint definitions");
        }
        String previousStable = blueprintToStable.putIfAbsent(
                blueprintName, nominal.stableId());
        if (previousStable != null && !previousStable.equals(nominal.stableId())) {
            throw projectedSchemaMismatch(path,
                    "multiple nominal IDs map to one blueprint definition");
        }
        var projected = projection.definitions().stream()
                .filter(candidate -> candidate.stableId().equals(nominal.stableId()))
                .findFirst().orElseThrow(() -> projectedSchemaMismatch(path,
                        "missing projected definition " + nominal.stableId()));
        if (projected.nominalKind() != nominal.nominalKind()
                || !projected.sourceName().equals(definition.path("title").asText())) {
            throw projectedSchemaMismatch(path, "nominal name or kind differs from blueprint");
        }

        JsonNode alternatives = definition.path("anyOf");
        if (!alternatives.isArray()) {
            throw projectedSchemaMismatch(path, "named definition has no constructor list");
        }
        if (nominal.nominalKind() == NominalTypeRef.NominalKind.RECORD) {
            if (alternatives.size() != 1) {
                throw projectedSchemaMismatch(path, "record must have one constructor");
            }
            matchProjectedConstructor(projected.sourceName(), 0, projected.fields(),
                    alternatives.get(0), projection, definitions, stableToBlueprint,
                    blueprintToStable, path);
        } else {
            if (alternatives.size() != projected.constructors().size()) {
                throw projectedSchemaMismatch(path, "sum constructor count differs");
            }
            for (int index = 0; index < projected.constructors().size(); index++) {
                var constructor = projected.constructors().get(index);
                matchProjectedConstructor(constructor.name(), constructor.tag(),
                        constructor.fields(), alternatives.get(index), projection, definitions,
                        stableToBlueprint, blueprintToStable,
                        path + "." + constructor.name());
            }
        }
    }

    private static void matchProjectedConstructor(
            String name,
            int tag,
            List<ProjectedContractTypes.Field> fields,
            JsonNode constructor,
            ProjectedContractTypes projection,
            Map<String, JsonNode> definitions,
            Map<String, String> stableToBlueprint,
            Map<String, String> blueprintToStable,
            String path) throws UnsupportedVerificationException {
        JsonNode publishedFields = constructor.path("fields");
        if (!isConstructor(constructor, name, tag, fields.size())) {
            throw projectedSchemaMismatch(path, "constructor tag, name, or arity differs");
        }
        for (int index = 0; index < fields.size(); index++) {
            var field = fields.get(index);
            JsonNode published = publishedFields.get(index);
            if (!field.name().equals(published.path("title").asText())) {
                throw projectedSchemaMismatch(path,
                        "field name/order differs at index " + index);
            }
            matchProjectedSchema(field.type(), published, projection, definitions,
                    stableToBlueprint, blueprintToStable, path + "." + field.name());
        }
    }

    private static UnsupportedVerificationException projectedSchemaMismatch(
            String path, String detail) {
        return new UnsupportedVerificationException(
                "Compiler-owned projected type graph does not match blueprint at "
                        + path + ": " + detail);
    }

    private static String containerSupport() {
        return """
                mutual
                  def dataDepth : Data → Nat
                    | Data.Constr _ fields => dataListDepth fields + 1
                    | Data.Map entries => dataMapDepth entries + 1
                    | Data.List items => dataListDepth items + 1
                    | Data.I _ => 1
                    | Data.B _ => 1

                  def dataListDepth : List Data → Nat
                    | [] => 0
                    | value :: rest => max (dataDepth value) (dataListDepth rest)

                  def dataMapDepth : List (Data × Data) → Nat
                    | [] => 0
                    | (key, value) :: rest =>
                        max (max (dataDepth key) (dataDepth value)) (dataMapDepth rest)
                end

                private def encodeOptionalWith (encode : α → Data) : Option α → Data
                  | none => mkDataConstr 1 []
                  | some value => mkDataConstr 0 [encode value]

                private def decodeOptionalWith
                    (decode : Data → Option α) : Data → Option (Option α)
                  | Data.Constr 1 [] => some none
                  | Data.Constr 0 [value] =>
                      match decode value with
                      | some decoded => some (some decoded)
                      | none => none
                  | _ => none

                /-- A Plutus `Data.List` whose elements all satisfy their CIP-57 schema. -/
                structure JulcList (α : Type) where
                  items : List α
                deriving Repr

                private def encodeJulcListWith
                    (encode : α → Data) : JulcList α → Data
                  | ⟨items⟩ => Data.List (items.map encode)

                private def decodeJulcListWith
                    (decode : Data → Option α) : Data → Option (JulcList α)
                  | Data.List values =>
                      let rec go : List Data → Option (List α)
                        | [] => some []
                        | value :: rest =>
                            match decode value, go rest with
                            | some decoded, some decodedRest =>
                                some (decoded :: decodedRest)
                            | _, _ => none
                      match go values with
                      | some decoded => some ⟨decoded⟩
                      | none => none
                  | _ => none

                private def decodeDataList [IsData α] : List Data → Option (List α)
                  | [] => some []
                  | value :: rest =>
                      match IsData.fromData value, decodeDataList rest with
                      | some decoded, some decodedRest => some (decoded :: decodedRest)
                      | _, _ => none

                private def encodeDataList [IsData α] : List α → List Data
                  | [] => []
                  | value :: rest => IsData.toData value :: encodeDataList rest

                instance [IsData α] : IsData (JulcList α) where
                  toData values := Data.List (encodeDataList values.items)
                  fromData
                  | Data.List values =>
                      match decodeDataList values with
                      | some decoded => some ⟨decoded⟩
                      | none => none
                  | _ => none

                /-- A Plutus `Data.Map`; ordered association-list entries are preserved. -/
                structure JulcMap (κ υ : Type) where
                  entries : List (κ × υ)
                deriving Repr

                private def decodeJulcMapWith
                    (decodeKey : Data → Option κ)
                    (decodeValue : Data → Option υ) : Data → Option (JulcMap κ υ)
                  | Data.Map entries =>
                      let rec go : List (Data × Data) → Option (List (κ × υ))
                        | [] => some []
                        | (key, value) :: rest =>
                            match decodeKey key, decodeValue value, go rest with
                            | some decodedKey, some decodedValue, some decodedRest =>
                                some ((decodedKey, decodedValue) :: decodedRest)
                            | _, _, _ => none
                      match go entries with
                      | some decoded => some ⟨decoded⟩
                      | none => none
                  | _ => none

                private def decodeDataMap [IsData κ] [IsData υ] :
                    List (Data × Data) → Option (List (κ × υ))
                  | [] => some []
                  | (key, value) :: rest =>
                      match IsData.fromData key, IsData.fromData value, decodeDataMap rest with
                      | some decodedKey, some decodedValue, some decodedRest =>
                          some ((decodedKey, decodedValue) :: decodedRest)
                      | _, _, _ => none

                private def encodeDataMap [IsData κ] [IsData υ] :
                    List (κ × υ) → List (Data × Data)
                  | [] => []
                  | (key, value) :: rest =>
                      (IsData.toData key, IsData.toData value) :: encodeDataMap rest

                instance [IsData κ] [IsData υ] : IsData (JulcMap κ υ) where
                  toData values := Data.Map (encodeDataMap values.entries)
                  fromData
                  | Data.Map entries =>
                      match decodeDataMap entries with
                      | some decoded => some ⟨decoded⟩
                      | none => none
                  | _ => none

                """;
    }

    private static String generateDefinition(
            String original,
            String typeName,
            Map<String, JsonNode> definitions,
            Map<String, String> names) throws UnsupportedVerificationException {
        List<Constructor> constructors = constructors(original, typeName, definitions, names);

        boolean structure = constructors.size() == 1 && !constructors.getFirst().fields().isEmpty();
        var out = new StringBuilder();
        if (structure) {
            Constructor ctor = constructors.getFirst();
            out.append("structure ").append(typeName).append(" where\n");
            for (Field field : ctor.fields()) {
                out.append("  ").append(field.name()).append(" : ").append(field.type()).append("\n");
            }
            out.append("deriving Repr\n\n")
                    .append("instance : IsData ").append(typeName).append(" where\n")
                    .append("  toData x := mkDataConstr ").append(ctor.index()).append(" ")
                    .append(dataList(ctor.fields(), field -> "IsData.toData x." + field.name()))
                    .append("\n")
                    .append("  fromData\n")
                    .append(fromDataBranch(ctor, "some { " + assignments(ctor.fields()) + " }"))
                    .append("  | _ => none\n\n");
        } else {
            out.append("inductive ").append(typeName).append(" where\n");
            appendConstructors(out, constructors, "  ");
            out.append("deriving Repr\n\n")
                    .append("instance : IsData ").append(typeName).append(" where\n")
                    .append("  toData\n");
            for (Constructor ctor : constructors) {
                out.append("  | .").append(ctor.name());
                for (Field field : ctor.fields()) {
                    out.append(" ").append(field.name());
                }
                out.append(" => mkDataConstr ").append(ctor.index()).append(" ")
                        .append(dataList(ctor.fields(), field -> "IsData.toData " + field.name()))
                        .append("\n");
            }
            out.append("  fromData\n");
            for (Constructor ctor : constructors) {
                String value = "some (." + ctor.name()
                        + ctor.fields().stream().map(field -> " " + field.name())
                        .reduce("", String::concat) + ")";
                out.append(fromDataBranch(ctor, value));
            }
            out.append("  | _ => none\n\n");
        }
        return out.toString();
    }

    private static List<Constructor> constructors(
            String original,
            String typeName,
            Map<String, JsonNode> definitions,
            Map<String, String> names) throws UnsupportedVerificationException {
        JsonNode schema = definitions.get(original);
        JsonNode alternatives = schema.path("anyOf");
        if (!alternatives.isArray() || alternatives.isEmpty()) {
            throw unsupported(original, schema);
        }

        List<Constructor> constructors = new ArrayList<>();
        Set<String> constructorNames = new HashSet<>();
        Set<Integer> constructorIndexes = new HashSet<>();
        for (JsonNode alternative : alternatives) {
            if (!"constructor".equals(alternative.path("dataType").asText())) {
                throw unsupported(original, alternative);
            }
            if (!alternative.path("index").canConvertToInt()) {
                throw new UnsupportedVerificationException(
                        "Constructor index is missing for schema definition '" + original + "'");
            }
            int constructorIndex = alternative.path("index").asInt();
            if (constructorIndex < 0 || !constructorIndexes.add(constructorIndex)) {
                throw new UnsupportedVerificationException(
                        "Constructor indexes must be unique and nonnegative in schema definition '"
                                + original + "'");
            }
            String title = alternative.path("title").asText(typeName);
            if (!hasIdentifierCharacters(title)) {
                throw new UnsupportedVerificationException(
                        "Constructor title cannot form a Lean identifier in schema definition '"
                                + original + "'");
            }
            String ctorName = leanTypeName(title);
            if (!constructorNames.add(ctorName)) {
                throw new UnsupportedVerificationException(
                        "Constructor names collide in schema definition '" + original + "'");
            }
            List<Field> fields = fields(original, alternative.path("fields"), definitions, names);
            constructors.add(new Constructor(ctorName, constructorIndex, fields));
        }
        return constructors;
    }

    private static void appendConstructors(
            StringBuilder out, List<Constructor> constructors, String indent) {
        for (Constructor ctor : constructors) {
            out.append(indent).append("| ").append(ctor.name());
            for (Field field : ctor.fields()) {
                out.append(" (").append(field.name()).append(" : ").append(field.type()).append(")");
            }
            out.append("\n");
        }
    }

    private static String generateRecursiveGroup(
            List<String> group,
            Map<String, JsonNode> definitions,
            Map<String, String> names) throws UnsupportedVerificationException {
        Set<String> members = Set.copyOf(group);
        var constructorsByType = new LinkedHashMap<String, List<Constructor>>();
        for (String original : group) {
            constructorsByType.put(original,
                    constructors(original, names.get(original), definitions, names));
        }

        var containers = new LinkedHashMap<String, RecursiveContainer>();
        for (var constructors : constructorsByType.values()) {
            for (Constructor constructor : constructors) {
                for (Field field : constructor.fields()) {
                    registerRecursiveContainers(
                            field.schema(), members, containers, names.get(group.getFirst()));
                }
            }
        }

        var out = new StringBuilder();
        if (group.size() == 1) {
            String original = group.getFirst();
            out.append("inductive ").append(names.get(original)).append(" where\n");
            appendConstructors(out, constructorsByType.get(original), "  ");
            out.append("deriving Repr\n\n");
        } else {
            out.append("mutual\n");
            for (String original : group) {
                out.append("  inductive ").append(names.get(original)).append(" where\n");
                appendConstructors(out, constructorsByType.get(original), "    ");
            }
            out.append("end\n\nderiving instance Repr for ")
                    .append(group.stream().map(names::get).reduce((a, b) -> a + ", " + b)
                            .orElseThrow())
                    .append("\n\n");
        }

        out.append("mutual\n");
        for (String original : group) {
            String typeName = names.get(original);
            out.append("  def encode").append(typeName).append(" : ")
                    .append(typeName).append(" → Data\n");
            for (Constructor constructor : constructorsByType.get(original)) {
                out.append("    | .").append(constructor.name());
                for (Field field : constructor.fields()) out.append(" ").append(field.name());
                out.append(" => mkDataConstr ").append(constructor.index()).append(" ")
                        .append(dataList(constructor.fields(), field -> encodeRecursiveSchema(
                                field.schema(), field.name(), members, names, containers)))
                        .append("\n");
            }
            out.append("\n");
        }
        for (RecursiveContainer container : containers.values()) {
            appendRecursiveContainerEncoder(
                    out, container, members, definitions, names, containers);
        }
        out.append("end\n\n");

        out.append("mutual\n");
        for (String original : group) {
            String typeName = names.get(original);
            out.append("  def decode").append(typeName)
                    .append(" : Nat → Data → Option ").append(typeName).append("\n")
                    .append("    | 0, _ => none\n");
            for (Constructor constructor : constructorsByType.get(original)) {
                boolean usesDepth = false;
                for (Field field : constructor.fields()) {
                    if (containsReferenceTo(field.schema(), members)) {
                        usesDepth = true;
                        break;
                    }
                }
                out.append("    | ").append(usesDepth ? "depth" : "_")
                        .append(" + 1, Data.Constr ").append(constructor.index()).append(" ")
                        .append(dataList(constructor.fields(), field -> "r_" + field.name()))
                        .append(" =>\n");
                if (constructor.fields().isEmpty()) {
                    out.append("        some (").append(typeName).append(".")
                            .append(constructor.name()).append(")\n");
                    continue;
                }
                var decodedFields = new ArrayList<String>();
                for (Field field : constructor.fields()) {
                    decodedFields.add(decodeRecursiveSchema(
                            field.schema(), "r_" + field.name(), "depth", members, names));
                }
                out.append("        match ")
                        .append(String.join(", ", decodedFields))
                        .append(" with\n        | ")
                        .append(constructor.fields().stream()
                                .map(field -> "some " + field.name())
                                .reduce((a, b) -> a + ", " + b).orElseThrow())
                        .append(" => some (").append(typeName).append(".")
                        .append(constructor.name())
                        .append(constructor.fields().stream()
                                .map(field -> " " + field.name()).reduce("", String::concat))
                        .append(")\n        | ")
                        .append(constructor.fields().stream().map(field -> "_")
                                .reduce((a, b) -> a + ", " + b).orElseThrow())
                        .append(" => none\n");
            }
            out.append("    | _ + 1, _ => none\n\n");
        }
        out.append("end\n\n");

        for (String original : group) {
            String typeName = names.get(original);
            out.append("instance : IsData ").append(typeName).append(" where\n")
                    .append("  toData := encode").append(typeName).append("\n")
                    .append("  fromData value := decode").append(typeName)
                    .append(" (dataDepth value + 1) value\n\n");
        }
        return out.toString();
    }

    private static void registerRecursiveContainers(
            JsonNode schema,
            Set<String> group,
            Map<String, RecursiveContainer> containers,
            String prefix) throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) return;
        JsonNode optional = optionalValueSchema(schema);
        String dataType = schema.path("dataType").asText();
        boolean container = dataType.equals("list") || dataType.equals("map") || optional != null;
        if (container && containsReferenceTo(schema, group)) {
            String key = schema.toString();
            containers.computeIfAbsent(key, ignored -> new RecursiveContainer(
                    "encode" + prefix + "Container" + containers.size(), schema));
        }
        if (dataType.equals("list")) {
            registerRecursiveContainers(schema.path("items"), group, containers, prefix);
        } else if (dataType.equals("map")) {
            registerRecursiveContainers(schema.path("keys"), group, containers, prefix);
            registerRecursiveContainers(schema.path("values"), group, containers, prefix);
        } else if (optional != null) {
            registerRecursiveContainers(optional, group, containers, prefix);
        }
    }

    private static boolean containsReferenceTo(JsonNode schema, Set<String> targets)
            throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) return targets.contains(referenceName(ref));
        JsonNode optional = optionalValueSchema(schema);
        if (optional != null && containsReferenceTo(optional, targets)) return true;
        for (String child : List.of("items", "keys", "values")) {
            JsonNode value = schema.path(child);
            if (!value.isMissingNode() && containsReferenceTo(value, targets)) return true;
        }
        return false;
    }

    private static String encodeRecursiveSchema(
            JsonNode schema,
            String value,
            Set<String> group,
            Map<String, String> names,
            Map<String, RecursiveContainer> containers)
            throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) {
            String referenced = referenceName(ref);
            if (group.contains(referenced)) return "encode" + names.get(referenced) + " " + value;
        }
        RecursiveContainer container = containers.get(schema.toString());
        if (container != null) return container.function() + " " + value;
        return "IsData.toData " + value;
    }

    private static String decodeRecursiveSchema(
            JsonNode schema,
            String data,
            String depth,
            Set<String> group,
            Map<String, String> names) throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) {
            String referenced = referenceName(ref);
            if (group.contains(referenced)) {
                return "decode" + names.get(referenced) + " " + depth + " " + data;
            }
            return "IsData.fromData " + data;
        }
        String dataType = schema.path("dataType").asText();
        if (dataType.equals("list") && containsReferenceTo(schema, group)) {
            return "decodeJulcListWith (fun value => "
                    + decodeRecursiveSchema(schema.path("items"), "value", depth, group, names)
                    + ") " + data;
        }
        if (dataType.equals("map") && containsReferenceTo(schema, group)) {
            return "decodeJulcMapWith (fun key => "
                    + decodeRecursiveSchema(schema.path("keys"), "key", depth, group, names)
                    + ") (fun value => "
                    + decodeRecursiveSchema(schema.path("values"), "value", depth, group, names)
                    + ") " + data;
        }
        JsonNode optional = optionalValueSchema(schema);
        if (optional != null && containsReferenceTo(schema, group)) {
            return "decodeOptionalWith (fun value => "
                    + decodeRecursiveSchema(optional, "value", depth, group, names)
                    + ") " + data;
        }
        return "IsData.fromData " + data;
    }

    private static void appendRecursiveContainerEncoder(
            StringBuilder out,
            RecursiveContainer container,
            Set<String> group,
            Map<String, JsonNode> definitions,
            Map<String, String> names,
            Map<String, RecursiveContainer> containers) throws UnsupportedVerificationException {
        JsonNode schema = container.schema();
        String dataType = schema.path("dataType").asText();
        String type = schemaType(schema, definitions, names, names.keySet().iterator().next());
        if (dataType.equals("list")) {
            JsonNode items = schema.path("items");
            String itemType = schemaType(items, definitions, names, "recursive-list");
            out.append("  def ").append(container.function()).append(" : ")
                    .append(type).append(" → Data\n")
                    .append("    | ⟨items⟩ => Data.List (").append(container.function())
                    .append("Items items)\n\n")
                    .append("  def ").append(container.function()).append("Items : List ")
                    .append(itemType).append(" → List Data\n")
                    .append("    | [] => []\n")
                    .append("    | value :: rest => ")
                    .append(encodeRecursiveSchema(items, "value", group, names, containers))
                    .append(" :: ").append(container.function()).append("Items rest\n\n");
            return;
        }
        if (dataType.equals("map")) {
            JsonNode keys = schema.path("keys");
            JsonNode values = schema.path("values");
            String keyType = schemaType(keys, definitions, names, "recursive-map-key");
            String valueType = schemaType(values, definitions, names, "recursive-map-value");
            out.append("  def ").append(container.function()).append(" : ")
                    .append(type).append(" → Data\n")
                    .append("    | ⟨entries⟩ => Data.Map (").append(container.function())
                    .append("Entries entries)\n\n")
                    .append("  def ").append(container.function())
                    .append("Entries : List (").append(keyType).append(" × ")
                    .append(valueType).append(") → List (Data × Data)\n")
                    .append("    | [] => []\n")
                    .append("    | (key, value) :: rest => (")
                    .append(encodeRecursiveSchema(keys, "key", group, names, containers))
                    .append(", ")
                    .append(encodeRecursiveSchema(values, "value", group, names, containers))
                    .append(") :: ").append(container.function()).append("Entries rest\n\n");
            return;
        }
        JsonNode optional = optionalValueSchema(schema);
        if (optional != null) {
            out.append("  def ").append(container.function()).append(" : ")
                    .append(type).append(" → Data\n")
                    .append("    | none => mkDataConstr 1 []\n")
                    .append("    | some value => mkDataConstr 0 [")
                    .append(encodeRecursiveSchema(optional, "value", group, names, containers))
                    .append("]\n\n");
            return;
        }
        throw new UnsupportedVerificationException("Unsupported recursive container schema");
    }

    private static String fromDataBranch(Constructor ctor, String success)
            throws UnsupportedVerificationException {
        var out = new StringBuilder("  | Data.Constr ")
                .append(ctor.index()).append(" ")
                .append(dataList(ctor.fields(), field -> "r_" + field.name()))
                .append(" =>\n");
        if (ctor.fields().isEmpty()) {
            return out.append("      ").append(success).append("\n").toString();
        }
        out.append("      match ")
                .append(ctor.fields().stream()
                        .map(field -> "IsData.fromData r_" + field.name())
                        .reduce((a, b) -> a + ", " + b).orElseThrow())
                .append(" with\n")
                .append("      | ")
                .append(ctor.fields().stream().map(field -> "some " + field.name())
                        .reduce((a, b) -> a + ", " + b).orElseThrow())
                .append(" => ").append(success).append("\n")
                .append("      | ")
                .append(ctor.fields().stream().map(field -> "_")
                        .reduce((a, b) -> a + ", " + b).orElseThrow())
                .append(" => none\n");
        return out.toString();
    }

    private static List<Field> fields(
            String owner,
            JsonNode fields,
            Map<String, JsonNode> definitions,
            Map<String, String> names) throws UnsupportedVerificationException {
        if (!fields.isArray()) {
            throw new UnsupportedVerificationException(
                    "Constructor fields must be an array in schema definition '" + owner + "'");
        }
        List<Field> result = new ArrayList<>();
        Set<String> fieldNames = new HashSet<>();
        int index = 0;
        for (JsonNode field : fields) {
            String rawName = field.path("title").asText("field" + index);
            if (!hasIdentifierCharacters(rawName)) {
                throw new UnsupportedVerificationException(
                        "Field title cannot form a Lean identifier in schema definition '"
                                + owner + "'");
            }
            String name = leanFieldName(rawName);
            if (!fieldNames.add(name)) {
                throw new UnsupportedVerificationException(
                        "Field names collide in schema definition '" + owner + "'");
            }
            result.add(new Field(
                    name, schemaType(field, definitions, names, owner), field));
            index++;
        }
        return result;
    }

    private static String schemaType(
            JsonNode schema,
            Map<String, JsonNode> definitions,
            Map<String, String> names,
            String owner) throws UnsupportedVerificationException {
        return schemaType(schema, definitions, names, owner, false);
    }

    private static String schemaType(
            JsonNode schema,
            Map<String, JsonNode> definitions,
            Map<String, String> names,
            String owner,
            boolean definitionRoot) throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) {
            String referenced = referenceName(ref);
            JsonNode target = definitions.get(referenced);
            if (target == null) {
                throw new UnsupportedVerificationException("Unknown schema reference '" + ref + "'");
            }
            String named = names.get(referenced);
            return named != null
                    ? named
                    : schemaType(target, definitions, names, referenced, true);
        }

        String primitive = primitiveType(schema);
        if (primitive != null) {
            return primitive;
        }

        return switch (schema.path("dataType").asText()) {
            case "list" -> {
                JsonNode items = schema.path("items");
                if (items.isMissingNode()) {
                    throw malformedContainer(owner, "list schema requires items");
                }
                yield "JulcList (" + schemaType(items, definitions, names, owner) + ")";
            }
            case "map" -> {
                JsonNode keys = schema.path("keys");
                JsonNode values = schema.path("values");
                if (keys.isMissingNode() || values.isMissingNode()) {
                    throw malformedContainer(owner, "map schema requires keys and values");
                }
                yield "JulcMap (" + schemaType(keys, definitions, names, owner) + ") ("
                        + schemaType(values, definitions, names, owner) + ")";
            }
            default -> {
                if (isBooleanSchema(schema)) {
                    yield "Bool";
                }
                JsonNode optionalValue = optionalValueSchema(schema);
                if (optionalValue != null) {
                    yield "Option (" + schemaType(optionalValue, definitions, names, owner) + ")";
                }
                String named = names.get(owner);
                if (named != null && definitionRoot) {
                    yield named;
                }
                throw new UnsupportedVerificationException(
                        "Inline or unsupported field schema in definition '" + owner + "'");
            }
        };
    }

    private static boolean requiresNamedDefinition(JsonNode schema) {
        return primitiveType(schema) == null
                && !"list".equals(schema.path("dataType").asText())
                && !"map".equals(schema.path("dataType").asText())
                && !isBooleanSchema(schema)
                && optionalValueSchema(schema) == null;
    }

    private static boolean isBooleanSchema(JsonNode schema) {
        JsonNode alternatives = schema.path("anyOf");
        return alternatives.isArray()
                && alternatives.size() == 2
                && isConstructor(alternatives.get(0), "False", 0, 0)
                && isConstructor(alternatives.get(1), "True", 1, 0);
    }

    private static JsonNode optionalValueSchema(JsonNode schema) {
        JsonNode alternatives = schema.path("anyOf");
        if (!alternatives.isArray() || alternatives.size() != 2
                || !isConstructor(alternatives.get(0), "Some", 0, 1)
                || !isConstructor(alternatives.get(1), "None", 1, 0)) {
            return null;
        }
        return alternatives.get(0).path("fields").get(0);
    }

    private static boolean isConstructor(
            JsonNode schema, String title, int index, int fieldCount) {
        JsonNode fields = schema.path("fields");
        return "constructor".equals(schema.path("dataType").asText())
                && title.equals(schema.path("title").asText())
                && schema.path("index").canConvertToInt()
                && schema.path("index").asInt() == index
                && fields.isArray()
                && fields.size() == fieldCount;
    }

    private static UnsupportedVerificationException malformedContainer(
            String owner, String detail) {
        return new UnsupportedVerificationException(
                "Malformed container schema in definition '" + owner + "': " + detail);
    }

    private static void collectInlineDependencies(
            JsonNode schema,
            String owner,
            Map<String, JsonNode> definitions,
            Set<String> needed,
            Set<String> active) throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) {
            collectNeeded(referenceName(ref), definitions, needed, active);
            return;
        }
        if (primitiveType(schema) != null) {
            return;
        }
        switch (schema.path("dataType").asText()) {
            case "list" -> {
                JsonNode items = schema.path("items");
                if (items.isMissingNode()) {
                    throw malformedContainer(owner, "list schema requires items");
                }
                collectInlineDependencies(items, owner, definitions, needed, active);
                return;
            }
            case "map" -> {
                JsonNode keys = schema.path("keys");
                JsonNode values = schema.path("values");
                if (keys.isMissingNode() || values.isMissingNode()) {
                    throw malformedContainer(owner, "map schema requires keys and values");
                }
                collectInlineDependencies(keys, owner, definitions, needed, active);
                collectInlineDependencies(values, owner, definitions, needed, active);
                return;
            }
            default -> {
                JsonNode alternatives = schema.path("anyOf");
                if (!alternatives.isArray() || alternatives.isEmpty()) {
                    throw unsupported(owner, schema);
                }
                for (JsonNode alternative : alternatives) {
                    if (!"constructor".equals(alternative.path("dataType").asText())) {
                        throw unsupported(owner, alternative);
                    }
                    JsonNode fields = alternative.path("fields");
                    if (!fields.isArray()) {
                        throw unsupported(owner, alternative);
                    }
                    for (JsonNode field : fields) {
                        collectInlineDependencies(field, owner, definitions, needed, active);
                    }
                }
            }
        }
    }

    private static String primitiveType(JsonNode schema) {
        return switch (schema.path("dataType").asText()) {
            case "integer" -> "Integer";
            case "bytes" -> "ByteString";
            default -> null;
        };
    }

    private static void collectEntrySchemaRoot(JsonNode schema, Set<String> roots)
            throws UnsupportedVerificationException {
        if (schema.isMissingNode()) {
            return;
        }
        String ref = schema.path("$ref").asText(null);
        if (ref == null) {
            throw new UnsupportedVerificationException(
                    "Entrypoint datum/redeemer schema must use a named definition reference");
        }
        roots.add(referenceName(ref));
    }

    private static void collectNeeded(
            String name,
            Map<String, JsonNode> definitions,
            Set<String> needed,
            Set<String> active) throws UnsupportedVerificationException {
        JsonNode schema = definitions.get(name);
        if (schema == null) {
            throw new UnsupportedVerificationException("Unknown schema definition '" + name + "'");
        }
        if (active.contains(name)) {
            return;
        }
        if (needed.contains(name)) {
            return;
        }
        active.add(name);
        collectInlineDependencies(schema, name, definitions, needed, active);
        active.remove(name);
        needed.add(name);
    }

    private static Map<String, Set<String>> namedDependencyGraph(
            Set<String> names, Map<String, JsonNode> definitions)
            throws UnsupportedVerificationException {
        var graph = new LinkedHashMap<String, Set<String>>();
        for (String name : names) {
            var dependencies = new LinkedHashSet<String>();
            collectNamedDependencies(
                    definitions.get(name), names, definitions, dependencies, new HashSet<>());
            graph.put(name, dependencies);
        }
        return graph;
    }

    private static void collectNamedDependencies(
            JsonNode schema,
            Set<String> names,
            Map<String, JsonNode> definitions,
            Set<String> dependencies,
            Set<String> activeAliases)
            throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) {
            String referenced = referenceName(ref);
            if (names.contains(referenced)) {
                dependencies.add(referenced);
                return;
            }
            JsonNode alias = definitions.get(referenced);
            if (alias == null) {
                throw new UnsupportedVerificationException(
                        "Unknown schema definition '" + referenced + "'");
            }
            if (activeAliases.add(referenced)) {
                collectNamedDependencies(
                        alias, names, definitions, dependencies, activeAliases);
                activeAliases.remove(referenced);
            }
            return;
        }
        for (String child : List.of("fields", "anyOf", "items", "keys", "values")) {
            JsonNode value = schema.path(child);
            if (value.isArray()) {
                for (JsonNode item : value) {
                    collectNamedDependencies(
                            item, names, definitions, dependencies, activeAliases);
                }
            } else if (!value.isMissingNode()) {
                collectNamedDependencies(
                        value, names, definitions, dependencies, activeAliases);
            }
        }
    }

    private static List<List<String>> dependencyGroups(Map<String, Set<String>> graph) {
        var index = new int[] {0};
        var indexes = new HashMap<String, Integer>();
        var lowLinks = new HashMap<String, Integer>();
        var stack = new ArrayDeque<String>();
        var onStack = new HashSet<String>();
        var components = new ArrayList<List<String>>();
        for (String node : graph.keySet()) {
            if (!indexes.containsKey(node)) {
                strongConnect(node, graph, index, indexes, lowLinks,
                        stack, onStack, components);
            }
        }

        var order = new HashMap<String, Integer>();
        int position = 0;
        for (String node : graph.keySet()) order.put(node, position++);
        components.forEach(component -> component.sort(Comparator.comparingInt(order::get)));

        var componentOf = new HashMap<String, Integer>();
        for (int i = 0; i < components.size(); i++) {
            for (String node : components.get(i)) componentOf.put(node, i);
        }
        var dependencies = new ArrayList<Set<Integer>>();
        var inDegree = new int[components.size()];
        for (int i = 0; i < components.size(); i++) dependencies.add(new LinkedHashSet<>());
        for (var entry : graph.entrySet()) {
            int owner = componentOf.get(entry.getKey());
            for (String dependency : entry.getValue()) {
                int target = componentOf.get(dependency);
                if (owner != target && dependencies.get(owner).add(target)) inDegree[owner]++;
            }
        }

        var ready = new PriorityQueue<Integer>(Comparator.comparingInt(component ->
                order.get(components.get(component).getFirst())));
        for (int i = 0; i < inDegree.length; i++) if (inDegree[i] == 0) ready.add(i);
        var result = new ArrayList<List<String>>();
        while (!ready.isEmpty()) {
            int completed = ready.remove();
            result.add(components.get(completed));
            for (int owner = 0; owner < dependencies.size(); owner++) {
                if (dependencies.get(owner).contains(completed) && --inDegree[owner] == 0) {
                    ready.add(owner);
                }
            }
        }
        return result;
    }

    private static void strongConnect(
            String node,
            Map<String, Set<String>> graph,
            int[] nextIndex,
            Map<String, Integer> indexes,
            Map<String, Integer> lowLinks,
            ArrayDeque<String> stack,
            Set<String> onStack,
            List<List<String>> components) {
        int nodeIndex = nextIndex[0]++;
        indexes.put(node, nodeIndex);
        lowLinks.put(node, nodeIndex);
        stack.push(node);
        onStack.add(node);
        for (String dependency : graph.getOrDefault(node, Set.of())) {
            if (!indexes.containsKey(dependency)) {
                strongConnect(dependency, graph, nextIndex, indexes, lowLinks,
                        stack, onStack, components);
                lowLinks.put(node, Math.min(lowLinks.get(node), lowLinks.get(dependency)));
            } else if (onStack.contains(dependency)) {
                lowLinks.put(node, Math.min(lowLinks.get(node), indexes.get(dependency)));
            }
        }
        if (lowLinks.get(node).equals(indexes.get(node))) {
            var component = new ArrayList<String>();
            String member;
            do {
                member = stack.pop();
                onStack.remove(member);
                component.add(member);
            } while (!member.equals(node));
            components.add(component);
        }
    }

    private static void validateProductiveSchemas(
            List<String> group, Map<String, JsonNode> definitions)
            throws UnsupportedVerificationException {
        Set<String> members = Set.copyOf(group);
        var productive = new LinkedHashSet<String>();
        boolean changed;
        do {
            changed = false;
            for (String name : group) {
                if (!productive.contains(name)
                        && schemaCanTerminate(definitions.get(name), members, productive)) {
                    productive.add(name);
                    changed = true;
                }
            }
        } while (changed);
        if (!productive.containsAll(group)) {
            var rejected = group.stream().filter(name -> !productive.contains(name)).toList();
            throw new UnsupportedVerificationException(
                    "Recursive schema has no finite base constructor: " + rejected);
        }
    }

    private static boolean schemaCanTerminate(
            JsonNode schema, Set<String> group, Set<String> productive)
            throws UnsupportedVerificationException {
        String ref = schema.path("$ref").asText(null);
        if (ref != null) {
            String referenced = referenceName(ref);
            return !group.contains(referenced) || productive.contains(referenced);
        }
        String dataType = schema.path("dataType").asText();
        if (dataType.equals("list") || dataType.equals("map")) return true;
        if (primitiveType(schema) != null || optionalValueSchema(schema) != null) return true;
        JsonNode alternatives = schema.path("anyOf");
        if (!alternatives.isArray()) return false;
        for (JsonNode alternative : alternatives) {
            JsonNode fields = alternative.path("fields");
            if (fields.isArray()) {
                boolean allProductive = true;
                for (JsonNode field : fields) {
                    if (!schemaCanTerminate(field, group, productive)) {
                        allProductive = false;
                        break;
                    }
                }
                if (allProductive) return true;
            }
        }
        return false;
    }

    private static JsonNode exactValidator(JsonNode blueprint, String title) {
        List<JsonNode> matches = new ArrayList<>();
        blueprint.path("validators").forEach(node -> {
            if (title.equals(node.path("title").asText(null))) {
                matches.add(node);
            }
        });
        if (matches.size() != 1) {
            throw new IllegalArgumentException(
                    "Expected exactly one validator titled '" + title + "', found " + matches.size());
        }
        return matches.getFirst();
    }

