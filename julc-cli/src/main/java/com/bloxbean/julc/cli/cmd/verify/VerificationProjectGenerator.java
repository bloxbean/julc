    private static void writeAtomically(Path output, Map<String, String> files)
            throws IOException {
        Path parent = output.getParent();
        if (parent == null) {
            throw new IllegalArgumentException("Output directory must have a parent");
        }
        Files.createDirectories(parent);
        Path staging = Files.createTempDirectory(parent, ".julc-verify-init-");
        try {
            for (var entry : files.entrySet()) {
                Path target = staging.resolve(entry.getKey());
                Files.createDirectories(target.getParent());
                Files.writeString(target, entry.getValue());
                if (entry.getKey().equals("scripts/verify.sh")) {
                    target.toFile().setExecutable(true, false);
                }
            }

            if (!Files.exists(output)) {
                Files.move(staging, output, StandardCopyOption.ATOMIC_MOVE);
                staging = null;
            } else {
                for (String relative : files.keySet()) {
                    Path source = staging.resolve(relative);
                    Path target = output.resolve(relative);
                    if (USER_OWNED_FILES.contains(relative) && Files.exists(target)) {
                        continue;
                    }
                    Files.createDirectories(target.getParent());
                    Files.copy(source, target, StandardCopyOption.REPLACE_EXISTING,
                            StandardCopyOption.COPY_ATTRIBUTES);
                }
            }
        } finally {
            if (staging != null && Files.exists(staging)) {
                deleteTree(staging);
            }
        }
    }

    private static void deleteTree(Path root) throws IOException {
        try (var paths = Files.walk(root)) {
            for (Path path : paths.sorted((a, b) -> b.compareTo(a)).toList()) {
                Files.deleteIfExists(path);
            }
        }
    }

    private static UnsupportedVerificationException unsupported(String name, JsonNode schema) {
        String kind = schema.path("dataType").asText(
                schema.has("anyOf") ? "constructor" : "unknown");
        return new UnsupportedVerificationException(
                "Unsupported schema form '" + kind + "' in definition '" + name + "'");
    }

    private static String referenceName(String ref) throws UnsupportedVerificationException {
        String prefix = "#/definitions/";
        if (!ref.startsWith(prefix) || ref.length() == prefix.length()) {
            throw new UnsupportedVerificationException("Unsupported schema reference '" + ref + "'");
        }
        return ref.substring(prefix.length())
                .replace("~1", "/")
                .replace("~0", "~");
    }

    private static String leanTypeName(String raw) {
        StringBuilder result = new StringBuilder();
        for (String part : raw.split("[^A-Za-z0-9]+")) {
            if (!part.isEmpty()) {
                result.append(Character.toUpperCase(part.charAt(0))).append(part.substring(1));
            }
        }
        if (result.isEmpty()) {
            result.append("GeneratedType");
        }
        if (Character.isDigit(result.charAt(0))) {
            result.insert(0, 'T');
        }
        return result.toString();
    }

    private static boolean hasIdentifierCharacters(String raw) {
        return raw != null && raw.chars().anyMatch(Character::isLetterOrDigit);
    }

    private static String leanFieldName(String raw) {
        String typeName = leanTypeName(raw);
        String result = Character.toLowerCase(typeName.charAt(0)) + typeName.substring(1);
        if (LEAN_RESERVED.contains(result.toLowerCase(Locale.ROOT))) {
            result += "Field";
        }
        return result;
    }

    private static String dataList(List<Field> fields, FieldRenderer renderer) {
        return "[" + fields.stream().map(renderer::render)
                .reduce((a, b) -> a + ", " + b).orElse("") + "]";
    }

    private static String assignments(List<Field> fields) {
        return fields.stream().map(field -> field.name() + " := " + field.name())
                .reduce((a, b) -> a + ", " + b).orElse("");
    }

    private static Set<Integer> supportedBuiltins() {
        Set<Integer> result = new HashSet<>();
        for (int tag = 0; tag <= 88; tag++) {
            result.add(tag);
        }
        result.add(92);
        result.add(93);
        return Set.copyOf(result);
    }

